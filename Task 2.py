from sklearn.feature_extraction.text import CountVectorizer
from sklearn.naive_bayes import MultinomialNB

# ---------------------------------------------------------------
# 0 = навчання, 1 = розваги, 2 = спам, 3 = оголошення
# ---------------------------------------------------------------

texts = [
    # --- НАВЧАННЯ (0) ---
    "Нагадую, що завтра о 10:00 лекція з машинного навчання, не запізнюйтесь.",
    "Надсилаю конспект з алгоритмів, якщо щось незрозуміло — пишіть.",
    "Домашнє завдання з математики треба здати до п'ятниці.",
    "Чи можемо перенести консультацію з викладачем на четвер?",
    "Підготував список літератури для курсової роботи, подивіться.",
    "Іспит з фізики буде в аудиторії 305, принесіть заліковки.",
    "Розклад пар на наступний тиждень уже оновлено на сайті.",
    "Хтось може пояснити тему з дискретної математики?",

    # --- РОЗВАГИ (1) ---
    "Хто йде на концерт у суботу? Є зайвий квиток!",
    "Дивилися новий фільм? Дуже раджу, смішний до сліз.",
    "Збираємось у п'ятницю в барі, приєднуйтесь!",
    "Граємо в настільні ігри ввечері, хто з нами?",
    "Є квитки на футбол, хто хоче піти разом?",
    "Плануємо похід у гори на вихідні, є вільне місце.",
    "Хто вже слухав новий альбом? Діліться враженнями!",
    "Зустрічаємось у кіно о восьмій, квитки вже куплені.",

    # --- СПАМ (2) ---
    "Вітаємо! Ви виграли безоплатний подарунок, скористайтеся нашою пропозицією!",
    "Терміново! Отримайте безоплатний кредит на ваш рахунок, не пропустіть!",
    "Спеціальна акція! Кешбек та цінний приз за вашу покупку, тільки сьогодні!",
    "Шановний користувачу! Надайте свої дані та виграйте гроші!",
    "Ваш рахунок заблоковано! Перейдіть за посиланням та підтвердіть дані.",
    "Тільки сьогодні! Безоплатний приз за реєстрацію на сайті!",
    "Ви переможець! Терміново надайте дані картки для отримання грошей!",
    "Акція! Виграйте цінний подарунок, перейдіть за посиланням!",

    # --- ОГОЛОШЕННЯ (3) ---
    "Продаю велосипед у хорошому стані, ціна договірна, пишіть у приват.",
    "Здається квартира на вулиці Шевченка, 2 кімнати, недорого.",
    "Шукаю репетитора з англійської мови для дитини, оплата погодинна.",
    "Віддам безкоштовно книжки, самовивіз з центру міста.",
    "Продаю ноутбук, 2021 рік, стан відмінний, можна домовитись про ціну.",
    "Куплю старий велосипед, можна в будь-якому стані.",
    "Оренда кімнати подобово в центрі, всі умови, ціна прийнятна.",
    "Продам дитячі книжки, недорого, самовивіз.",
]

labels = [0]*8 + [1]*8 + [2]*8 + [3]*8

var_vex = CountVectorizer()
x = var_vex.fit_transform(texts)
model = MultinomialNB().fit(x, labels)

class_names = {0: "НАВЧАННЯ", 1: "РОЗВАГИ", 2: "СПАМ", 3: "ОГОЛОШЕННЯ"}

# --- Tricky tests: cases designed to fool one approach or the other ---
tests = [
    # Straightforward correct cases
    "Завтра пара з фізики, принесіть зошити.",                # навчання
    "Хто хоче піти в кіно ввечері?",                          # розваги
    "Термінова акція: безоплатний кредит для вас!",           # спам
    "Продаю диван, недорого, самовивіз.",                     # оголошення

    # Tricky #1 — "квиток" is a розваги keyword, but this is clearly spam
    "Виграйте квиток на концерт! Надайте свої дані!",          # спам (tricky), Keywords search for квиток, концерт and ignore Виграйте, because it is not a keyword, while ML has надайте свої дані, свої дані, дані, виграйте, на and more repetitions of these words, which just means ML was better trained for these situations

    # Tricky #2 — "акція" is a спам keyword, but this is a legit announcement
    "Оголошення: акція на репетиторство, знижки для студентів.", # оголошення (tricky), Both got it wrong, the акція and знижки really tip the scale for spam

    # Tricky #3 — "гра" could be розваги; "шукаю" could be оголошення
    "Шукаю людей на настільні ігри, приєднуйтесь!",            # розваги (tricky)

    # Tricky #4 — positive-sounding spam
    "Вітаємо, ви переможець, отримайте безоплатний приз!",     # спам (tricky)

    # Tricky #5 — has "лекція" (навчання) but also "квиток" (розваги)
    "Після лекції йдемо в кіно, хто з нами?",                  # розваги (tricky)

    # Tricky #6 — no known keywords at all
    "Привіт, як справи?",                                     # ? (out of domain), different results, because ML ALWAYS outputs a guess, even if all options have the same probability, while the no ML way has a check to make sure it doesnt output a guess if it is unsure
]

# ---------------------------------------------------------------
# ML side
# ---------------------------------------------------------------
print("=== ML (Naive Bayes) ===")
ml_preds = model.predict(var_vex.transform(tests))
for text, pred in zip(tests, ml_preds):
    print(f"[{class_names[pred]:10}] {text}")

# ---------------------------------------------------------------
# Rule side
# ---------------------------------------------------------------
topic_keywords = {
    "навчання": [
        "лекція", "пара", "завдання", "конспект", "іспит", "курсова",
        "викладач", "навчання", "домашнє", "зошит", "програмування",
        "математика", "фізика", "розклад", "аудиторія"
    ],
    "розваги": [
        "концерт", "фільм", "кіно", "бар", "вечірка", "гра", "футбол",
        "квиток", "розвага", "настільні", "зустрічаємось", "гори", "альбом"
    ],
    "спам": [
        "виграли", "безоплатний", "кредит", "акція", "подарунок", "кешбек",
        "приз", "терміново", "заблоковано", "посиланням", "гроші", "дані",
        "переможець", "реєстрацію", "картки"
    ],
    "оголошення": [
        "продаю", "продам", "здається", "шукаю", "віддам", "самовивіз",
        "ціна", "недорого", "подобово", "куплю", "оренда", "репетитора",
        "диван", "квартира"
    ]
}

def rule_classifier(line):
    line = line.lower()
    scores = {topic: sum(word in line for word in words)
              for topic, words in topic_keywords.items()}
    best_topic, best_score = max(scores.items(), key=lambda item: item[1])
    if best_score == 0:
        return "невідомо"
    return best_topic

print("\n=== Rule-based ===")
for text in tests:
    print(f"[{rule_classifier(text):10}] {text}")

# ---------------------------------------------------------------
# Side-by-side comparison
# ---------------------------------------------------------------
print("\n=== Side by side ===")
for text, ml_pred in zip(tests, ml_preds):
    rule_pred = rule_classifier(text)
    ml_label = class_names[ml_pred]
    mark = "" if ml_label == rule_pred.upper() else "  <-- differ"
    print(f"ML: {ml_label:10} | Rule: {rule_pred:10} | {text}{mark}")